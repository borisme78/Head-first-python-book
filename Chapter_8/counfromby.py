class CountFromBy:
    """Простий лічильник, який збільшується на фіксований крок.

    Цей клас призначений для початківців, щоб показати, як простий
    об'єкт може зберігати стан (`val`) і змінювати його за допомогою методу
    (`increase`).

    Атрибути:
        val (int): Поточне числове значення лічильника.
        incr (int): Кількість, яка додається до `val` при кожному виклику `increase()`.

    Приклад:
        c = CountFromBy(10, 2)
        c.increase()  # c.val стає 12
    """

    def __init__(self, v: int = 0, i: int = 0):
        """Ініціалізує лічильник.

        Аргументи:
            v (int): початкове значення (за замовчуванням 0).
            i (int): крок збільшення (за замовчуванням 0).
        """
        # `val` зберігає поточне значення лічильника
        self.val = v
        # `incr` — на скільки збільшувати при виклику increase()
        self.incr = i

    def increase(self) -> None:
        """Збільшити лічильник на заданий крок.

        Цей метод змінює стан об'єкта на місці (без повернення значення).
        """
        self.val += self.incr

    def __repr__(self) -> str:
        """Повернути інформативне рядкове представлення для відладки.

        Для початківців `__repr__` показує важливий внутрішній стан,
        тому друк об'єкта буде зрозумілим.
        """
        return f"CountFromBy(val={self.val}, incr={self.incr})"